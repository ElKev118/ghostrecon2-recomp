/**
 * Ghost Recon 2 port - the window's post passes (vk_post.h).
 *
 * Full-screen triangles, dynamic rendering, sources bound with push
 * descriptors. Runs on the window thread, in its present command buffer,
 * after that thread's fence: what only these passes use (SMAA's images) is
 * idle whenever vkp_* runs.
 *
 *   scaling  the frame onto the swapchain image (area or bilinear)
 *   SMAA     iryoku/smaa 1x (MIT), its three passes on the frame at the
 *            internal resolution: luma edges, blending weights (area and
 *            search textures), neighbourhood blending
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "vk_post.h"
#include "vk_glsl.h"
#include "vk_ctx.h"
#include "smaa_hlsl.h"     /* SMAA_HLSL: SMAA.hlsl, generated by CMakeLists.txt */
#include "AreaTex.h"
#include "SearchTex.h"

/* ---- shaders ------------------------------------------------------------ */

static const char *VS =
    "#version 450\n"
    "layout(location = 0) out vec2 uv;\n"
    "void main() {\n"
    "  vec2 p = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2);\n"
    "  uv = p;\n"
    "  gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);\n"
    "}\n";

/* AREA: each output pixel is the mean of the source over its footprint,
 * from n x n bilinear taps spread evenly across it (n = the shrink factor,
 * rounded up, at most 8 per axis) -- a box filter as wide as the pixel.
 * At 1x or when enlarging it is a single bilinear tap. */
static const char *FS =
    "#version 450\n"
    "layout(location = 0) in vec2 uv;\n"
    "layout(location = 0) out vec4 o;\n"
    "layout(set = 0, binding = 0) uniform sampler2D src;\n"
    "layout(push_constant) uniform P { vec2 src_size; vec2 dst_size; int filt; } pc;\n"
    "void main() {\n"
    "  vec2 ratio = pc.src_size / pc.dst_size;\n"
    "  if (pc.filt == 0 || (ratio.x <= 1.0 && ratio.y <= 1.0)) {\n"
    "    o = vec4(texture(src, uv).rgb, 1.0);\n"
    "    return;\n"
    "  }\n"
    "  ivec2 n = clamp(ivec2(ceil(ratio)), ivec2(1), ivec2(8));\n"
    "  vec2 foot = 1.0 / pc.dst_size;\n"
    "  vec3 acc = vec3(0.0);\n"
    "  for (int j = 0; j < n.y; j++)\n"
    "    for (int i = 0; i < n.x; i++) {\n"
    "      vec2 f = (vec2(i, j) + 0.5) / vec2(n) - 0.5;\n"
    "      acc += texture(src, uv + f * foot).rgb;\n"
    "    }\n"
    "  o = vec4(acc / float(n.x * n.y), 1.0);\n"
    "}\n";

/* SMAA: every stage is this prefix, SMAA.hlsl, then its main. */
static const char *SMAA_PRE_VS =
    "#version 450\n"
    "layout(push_constant) uniform SP { vec4 metrics; } pc;\n"
    "#define SMAA_RT_METRICS pc.metrics\n"
    "#define SMAA_GLSL_4 1\n"
    "#define SMAA_PRESET_HIGH 1\n"
    "#define SMAA_INCLUDE_VS 1\n"
    "#define SMAA_INCLUDE_PS 0\n";
static const char *SMAA_PRE_FS =
    "#version 450\n"
    "layout(push_constant) uniform SP { vec4 metrics; } pc;\n"
    "#define SMAA_RT_METRICS pc.metrics\n"
    "#define SMAA_GLSL_4 1\n"
    "#define SMAA_PRESET_HIGH 1\n"
    "#define SMAA_INCLUDE_VS 0\n"
    "#define SMAA_INCLUDE_PS 1\n";
#define TRI "  tc = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2);\n" \
            "  gl_Position = vec4(tc * 2.0 - 1.0, 0.0, 1.0);\n"
static const char *EDGE_VS =
    "layout(location = 0) out vec2 tc;\n"
    "layout(location = 1) out vec4 off[3];\n"
    "void main() {\n" TRI "  SMAAEdgeDetectionVS(tc, off);\n}\n";
static const char *EDGE_FS =
    "layout(location = 0) in vec2 tc;\n"
    "layout(location = 1) in vec4 off[3];\n"
    "layout(set = 0, binding = 0) uniform sampler2D colorTex;\n"
    "layout(location = 0) out vec2 o;\n"
    "void main() { o = SMAALumaEdgeDetectionPS(tc, off, colorTex); }\n";
static const char *BLEND_VS =
    "layout(location = 0) out vec2 tc;\n"
    "layout(location = 1) out vec2 pix;\n"
    "layout(location = 2) out vec4 off[3];\n"
    "void main() {\n" TRI "  SMAABlendingWeightCalculationVS(tc, pix, off);\n}\n";
static const char *BLEND_FS =
    "layout(location = 0) in vec2 tc;\n"
    "layout(location = 1) in vec2 pix;\n"
    "layout(location = 2) in vec4 off[3];\n"
    "layout(set = 0, binding = 0) uniform sampler2D edgesTex;\n"
    "layout(set = 0, binding = 1) uniform sampler2D areaTex;\n"
    "layout(set = 0, binding = 2) uniform sampler2D searchTex;\n"
    "layout(location = 0) out vec4 o;\n"
    "void main() {\n"
    "  o = SMAABlendingWeightCalculationPS(tc, pix, off, edgesTex, areaTex, searchTex, vec4(0.0));\n"
    "}\n";
static const char *NEIGH_VS =
    "layout(location = 0) out vec2 tc;\n"
    "layout(location = 1) out vec4 off;\n"
    "void main() {\n" TRI "  SMAANeighborhoodBlendingVS(tc, off);\n}\n";
static const char *NEIGH_FS =
    "layout(location = 0) in vec2 tc;\n"
    "layout(location = 1) in vec4 off;\n"
    "layout(set = 0, binding = 0) uniform sampler2D colorTex;\n"
    "layout(set = 0, binding = 1) uniform sampler2D blendTex;\n"
    "layout(location = 0) out vec4 o;\n"
    "void main() { o = vec4(SMAANeighborhoodBlendingPS(tc, off, colorTex, blendTex).rgb, 1.0); }\n";

typedef struct { float src_size[2], dst_size[2]; int32_t filt; } Push;

typedef struct {
    VkImage img;
    VkDeviceMemory mem;
    VkImageView view;
    VkImageLayout layout;
} Img;

enum { SM_EDGE, SM_BLEND, SM_NEIGH, SM_N };

static struct {
    VkDevice dev;
    PFN_vkCmdPushDescriptorSetKHR push_desc;
    VkSampler lin, point;

    /* scaling */
    VkDescriptorSetLayout dsl;
    VkPipelineLayout layout;
    VkShaderModule vs, fs;
    VkPipeline pipe;
    VkFormat fmt;
    int ok;

    /* SMAA */
    int sm_tried, sm_ok;
    VkDescriptorSetLayout sm_dsl;
    VkPipelineLayout sm_layout;
    VkPipeline sm_pipe[SM_N];
    Img area, search, edges, blend, out;
    VkBuffer stage;
    VkDeviceMemory stage_mem;
    int tex_uploaded;
    uint32_t sm_w, sm_h;
} P;

static VkShaderModule module(const char *src, int frag)
{
    size_t bytes = 0;
    uint32_t *code = vkg_compile(src, frag, &bytes);
    VkShaderModuleCreateInfo ci = { VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO };
    VkShaderModule m = VK_NULL_HANDLE;

    if (!code)
        return VK_NULL_HANDLE;
    ci.codeSize = bytes;
    ci.pCode = code;
    vkCreateShaderModule(P.dev, &ci, NULL, &m);
    free(code);
    return m;
}

/* An SMAA stage: prefix + SMAA.hlsl + main. */
static VkShaderModule smaa_module(const char *main_src, int frag)
{
    const char *pre = frag ? SMAA_PRE_FS : SMAA_PRE_VS;
    size_t n = strlen(pre) + sizeof SMAA_HLSL + strlen(main_src) + 2;
    char *src = (char *)malloc(n);
    VkShaderModule m;

    if (!src)
        return VK_NULL_HANDLE;
    snprintf(src, n, "%s%s\n%s", pre, SMAA_HLSL, main_src);
    m = module(src, frag);
    free(src);
    return m;
}

static VkPipeline make_pipeline(VkShaderModule vs, VkShaderModule fs,
                                VkPipelineLayout layout, VkFormat fmt)
{
    VkPipelineShaderStageCreateInfo st[2];
    VkPipelineVertexInputStateCreateInfo vi = { VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO };
    VkPipelineInputAssemblyStateCreateInfo ia = { VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO };
    VkPipelineViewportStateCreateInfo vp = { VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO };
    VkPipelineRasterizationStateCreateInfo rs = { VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO };
    VkPipelineMultisampleStateCreateInfo ms = { VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO };
    VkPipelineColorBlendAttachmentState cba;
    VkPipelineColorBlendStateCreateInfo cb = { VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO };
    VkDynamicState dyn[2] = { VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR };
    VkPipelineDynamicStateCreateInfo ds = { VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO };
    VkPipelineRenderingCreateInfo rci = { VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO };
    VkGraphicsPipelineCreateInfo gp = { VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO };
    VkPipeline pipe = VK_NULL_HANDLE;

    if (!vs || !fs)
        return VK_NULL_HANDLE;
    memset(st, 0, sizeof st);
    st[0].sType = st[1].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    st[0].stage = VK_SHADER_STAGE_VERTEX_BIT;
    st[0].module = vs;
    st[0].pName = "main";
    st[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
    st[1].module = fs;
    st[1].pName = "main";
    ia.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;
    vp.viewportCount = 1;
    vp.scissorCount = 1;
    rs.polygonMode = VK_POLYGON_MODE_FILL;
    rs.cullMode = VK_CULL_MODE_NONE;
    rs.lineWidth = 1.0f;
    ms.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;
    memset(&cba, 0, sizeof cba);
    cba.colorWriteMask = 0xF;
    cb.attachmentCount = 1;
    cb.pAttachments = &cba;
    ds.dynamicStateCount = 2;
    ds.pDynamicStates = dyn;
    rci.colorAttachmentCount = 1;
    rci.pColorAttachmentFormats = &fmt;
    gp.pNext = &rci;
    gp.stageCount = 2;
    gp.pStages = st;
    gp.pVertexInputState = &vi;
    gp.pInputAssemblyState = &ia;
    gp.pViewportState = &vp;
    gp.pRasterizationState = &rs;
    gp.pMultisampleState = &ms;
    gp.pColorBlendState = &cb;
    gp.pDynamicState = &ds;
    gp.layout = layout;
    if (vkCreateGraphicsPipelines(P.dev, VK_NULL_HANDLE, 1, &gp, NULL, &pipe) != VK_SUCCESS)
        return VK_NULL_HANDLE;
    return pipe;
}

static void barrier(VkCommandBuffer cmd, Img *im, VkImageLayout to)
{
    VkImageMemoryBarrier b = { VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER };
    b.srcAccessMask = VK_ACCESS_MEMORY_WRITE_BIT;
    b.dstAccessMask = VK_ACCESS_MEMORY_READ_BIT | VK_ACCESS_MEMORY_WRITE_BIT;
    b.oldLayout = im->layout;
    b.newLayout = to;
    b.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    b.image = im->img;
    b.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
    b.subresourceRange.levelCount = 1;
    b.subresourceRange.layerCount = 1;
    vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_ALL_COMMANDS_BIT,
                         VK_PIPELINE_STAGE_ALL_COMMANDS_BIT, 0, 0, NULL, 0, NULL, 1, &b);
    im->layout = to;
}

static void free_img(Img *im)
{
    if (im->view) vkDestroyImageView(P.dev, im->view, NULL);
    if (im->img) vkDestroyImage(P.dev, im->img, NULL);
    if (im->mem) vkFreeMemory(P.dev, im->mem, NULL);
    memset(im, 0, sizeof *im);
}

static int make_img(Img *im, uint32_t w, uint32_t h, VkFormat fmt, VkImageUsageFlags usage)
{
    VkImageCreateInfo ici = { VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO };
    VkImageViewCreateInfo vci = { VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO };
    VkMemoryAllocateInfo mai = { VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO };
    VkMemoryRequirements mr;

    free_img(im);
    ici.imageType = VK_IMAGE_TYPE_2D;
    ici.format = fmt;
    ici.extent.width = w;
    ici.extent.height = h;
    ici.extent.depth = 1;
    ici.mipLevels = 1;
    ici.arrayLayers = 1;
    ici.samples = VK_SAMPLE_COUNT_1_BIT;
    ici.tiling = VK_IMAGE_TILING_OPTIMAL;
    ici.usage = usage | VK_IMAGE_USAGE_SAMPLED_BIT;
    if (vkCreateImage(P.dev, &ici, NULL, &im->img) != VK_SUCCESS)
        return 0;
    vkGetImageMemoryRequirements(P.dev, im->img, &mr);
    mai.allocationSize = mr.size;
    mai.memoryTypeIndex = vkw_find_memory(mr.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (vkAllocateMemory(P.dev, &mai, NULL, &im->mem) != VK_SUCCESS)
        return 0;
    vkBindImageMemory(P.dev, im->img, im->mem, 0);
    vci.image = im->img;
    vci.viewType = VK_IMAGE_VIEW_TYPE_2D;
    vci.format = fmt;
    vci.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
    vci.subresourceRange.levelCount = 1;
    vci.subresourceRange.layerCount = 1;
    if (vkCreateImageView(P.dev, &vci, NULL, &im->view) != VK_SUCCESS)
        return 0;
    im->layout = VK_IMAGE_LAYOUT_UNDEFINED;
    return 1;
}

/* Begin rendering into im (cleared), viewport = the whole image. */
static void begin_into(VkCommandBuffer cmd, Img *im, uint32_t w, uint32_t h)
{
    VkRenderingAttachmentInfo ca = { VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO };
    VkRenderingInfo ri = { VK_STRUCTURE_TYPE_RENDERING_INFO };
    VkViewport vp = { 0.0f, 0.0f, (float)w, (float)h, 0.0f, 1.0f };
    VkRect2D sc = { { 0, 0 }, { w, h } };

    barrier(cmd, im, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL);
    ca.imageView = im->view;
    ca.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    ca.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;       /* edge detection discards */
    ca.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
    ri.renderArea = sc;
    ri.layerCount = 1;
    ri.colorAttachmentCount = 1;
    ri.pColorAttachments = &ca;
    vkCmdBeginRendering(cmd, &ri);
    vkCmdSetViewport(cmd, 0, 1, &vp);
    vkCmdSetScissor(cmd, 0, 1, &sc);
}

static void bind_tex(VkCommandBuffer cmd, VkPipelineLayout layout, int n,
                     const VkImageView *views, const VkSampler *samps)
{
    VkDescriptorImageInfo ii[3];
    VkWriteDescriptorSet w = { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET };
    int i;
    for (i = 0; i < n; i++) {
        ii[i].sampler = samps[i];
        ii[i].imageView = views[i];
        ii[i].imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
    }
    w.dstBinding = 0;
    w.descriptorCount = (uint32_t)n;
    w.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
    w.pImageInfo = ii;
    P.push_desc(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, layout, 0, 1, &w);
}

/* ---- init --------------------------------------------------------------- */

int vkp_init(VkDevice dev, VkFormat target_format)
{
    VkSamplerCreateInfo sci = { VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO };
    VkDescriptorSetLayoutBinding b = { 0, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1,
                                       VK_SHADER_STAGE_FRAGMENT_BIT, NULL };
    VkDescriptorSetLayoutCreateInfo dli = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO };
    VkPushConstantRange pcr = { VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(Push) };
    VkPipelineLayoutCreateInfo pli = { VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };

    P.dev = dev;
    P.push_desc = (PFN_vkCmdPushDescriptorSetKHR)vkGetDeviceProcAddr(dev, "vkCmdPushDescriptorSetKHR");
    sci.magFilter = sci.minFilter = VK_FILTER_LINEAR;
    sci.addressModeU = sci.addressModeV = sci.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    sci.maxLod = 0.0f;
    dli.flags = VK_DESCRIPTOR_SET_LAYOUT_CREATE_PUSH_DESCRIPTOR_BIT_KHR;
    dli.bindingCount = 1;
    dli.pBindings = &b;
    pli.setLayoutCount = 1;
    pli.pSetLayouts = &P.dsl;
    pli.pushConstantRangeCount = 1;
    pli.pPushConstantRanges = &pcr;
    if (!P.push_desc
        || vkCreateSampler(dev, &sci, NULL, &P.lin) != VK_SUCCESS
        || vkCreateDescriptorSetLayout(dev, &dli, NULL, &P.dsl) != VK_SUCCESS
        || vkCreatePipelineLayout(dev, &pli, NULL, &P.layout) != VK_SUCCESS
        || !(P.vs = module(VS, 0)) || !(P.fs = module(FS, 1))
        || !(P.pipe = make_pipeline(P.vs, P.fs, P.layout, target_format))) {
        fprintf(stderr, "[VKP] scaling pass unavailable; the window blits instead\n");
        return 0;
    }
    sci.magFilter = sci.minFilter = VK_FILTER_NEAREST;
    vkCreateSampler(dev, &sci, NULL, &P.point);
    P.fmt = target_format;
    P.ok = 1;
    return 1;
}

static int smaa_init(void)
{
    VkDescriptorSetLayoutBinding b[3];
    VkDescriptorSetLayoutCreateInfo dli = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO };
    VkPushConstantRange pcr = { VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, 0, 16 };
    VkPipelineLayoutCreateInfo pli = { VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
    static const char *vs_src[SM_N], *fs_src[SM_N];
    static const VkFormat fmts[SM_N] = { VK_FORMAT_R8G8_UNORM, VK_FORMAT_R8G8B8A8_UNORM,
                                         VK_FORMAT_B8G8R8A8_UNORM };
    VkBufferCreateInfo bci = { VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO };
    VkMemoryAllocateInfo mai = { VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO };
    VkMemoryRequirements mr;
    void *map;
    int i;

    P.sm_tried = 1;
    vs_src[SM_EDGE] = EDGE_VS;  fs_src[SM_EDGE] = EDGE_FS;
    vs_src[SM_BLEND] = BLEND_VS; fs_src[SM_BLEND] = BLEND_FS;
    vs_src[SM_NEIGH] = NEIGH_VS; fs_src[SM_NEIGH] = NEIGH_FS;
    for (i = 0; i < 3; i++) {
        b[i].binding = (uint32_t)i;
        b[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        b[i].descriptorCount = 1;
        b[i].stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
        b[i].pImmutableSamplers = NULL;
    }
    dli.flags = VK_DESCRIPTOR_SET_LAYOUT_CREATE_PUSH_DESCRIPTOR_BIT_KHR;
    dli.bindingCount = 3;
    dli.pBindings = b;
    pli.setLayoutCount = 1;
    pli.pSetLayouts = &P.sm_dsl;
    pli.pushConstantRangeCount = 1;
    pli.pPushConstantRanges = &pcr;
    if (vkCreateDescriptorSetLayout(P.dev, &dli, NULL, &P.sm_dsl) != VK_SUCCESS
        || vkCreatePipelineLayout(P.dev, &pli, NULL, &P.sm_layout) != VK_SUCCESS)
        return 0;
    for (i = 0; i < SM_N; i++) {
        VkShaderModule vs = smaa_module(vs_src[i], 0), fs = smaa_module(fs_src[i], 1);
        P.sm_pipe[i] = make_pipeline(vs, fs, P.sm_layout, fmts[i]);
        if (vs) vkDestroyShaderModule(P.dev, vs, NULL);
        if (fs) vkDestroyShaderModule(P.dev, fs, NULL);
        if (!P.sm_pipe[i])
            return 0;
    }
    /* The precomputed area (RG8) and search (R8) textures, staged once. */
    if (!make_img(&P.area, AREATEX_WIDTH, AREATEX_HEIGHT, VK_FORMAT_R8G8_UNORM,
                  VK_IMAGE_USAGE_TRANSFER_DST_BIT)
        || !make_img(&P.search, SEARCHTEX_WIDTH, SEARCHTEX_HEIGHT, VK_FORMAT_R8_UNORM,
                     VK_IMAGE_USAGE_TRANSFER_DST_BIT))
        return 0;
    bci.size = sizeof areaTexBytes + sizeof searchTexBytes;
    bci.usage = VK_BUFFER_USAGE_TRANSFER_SRC_BIT;
    if (vkCreateBuffer(P.dev, &bci, NULL, &P.stage) != VK_SUCCESS)
        return 0;
    vkGetBufferMemoryRequirements(P.dev, P.stage, &mr);
    mai.allocationSize = mr.size;
    mai.memoryTypeIndex = vkw_find_memory(mr.memoryTypeBits,
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    if (vkAllocateMemory(P.dev, &mai, NULL, &P.stage_mem) != VK_SUCCESS)
        return 0;
    vkBindBufferMemory(P.dev, P.stage, P.stage_mem, 0);
    if (vkMapMemory(P.dev, P.stage_mem, 0, VK_WHOLE_SIZE, 0, &map) != VK_SUCCESS)
        return 0;
    memcpy(map, areaTexBytes, sizeof areaTexBytes);
    memcpy((uint8_t *)map + sizeof areaTexBytes, searchTexBytes, sizeof searchTexBytes);
    vkUnmapMemory(P.dev, P.stage_mem);
    fprintf(stderr, "[VKP] SMAA 1x (high preset) ready\n");
    return 1;
}

/* ---- SMAA --------------------------------------------------------------- */

VkImageView vkp_smaa(VkCommandBuffer cmd, VkImageView src, uint32_t w, uint32_t h)
{
    float metrics[4];

    if (!P.ok || !src || !w || !h)
        return src;
    if (!P.sm_tried && !(P.sm_ok = smaa_init()))
        fprintf(stderr, "[VKP] SMAA unavailable\n");
    if (!P.sm_ok)
        return src;
    if (!P.tex_uploaded) {
        VkBufferImageCopy c;
        memset(&c, 0, sizeof c);
        c.imageSubresource.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
        c.imageSubresource.layerCount = 1;
        c.imageExtent.depth = 1;
        barrier(cmd, &P.area, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);
        barrier(cmd, &P.search, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);
        c.imageExtent.width = AREATEX_WIDTH;
        c.imageExtent.height = AREATEX_HEIGHT;
        vkCmdCopyBufferToImage(cmd, P.stage, P.area.img, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &c);
        c.bufferOffset = sizeof areaTexBytes;
        c.imageExtent.width = SEARCHTEX_WIDTH;
        c.imageExtent.height = SEARCHTEX_HEIGHT;
        vkCmdCopyBufferToImage(cmd, P.stage, P.search.img, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &c);
        barrier(cmd, &P.area, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
        barrier(cmd, &P.search, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
        P.tex_uploaded = 1;
    }
    if (P.sm_w != w || P.sm_h != h) {
        /* Only these passes use them, and the window's last command buffer
         * has finished (its fence): safe to replace. */
        if (!make_img(&P.edges, w, h, VK_FORMAT_R8G8_UNORM, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT)
            || !make_img(&P.blend, w, h, VK_FORMAT_R8G8B8A8_UNORM, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT)
            || !make_img(&P.out, w, h, VK_FORMAT_B8G8R8A8_UNORM, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT)) {
            fprintf(stderr, "[VKP] SMAA images %ux%u failed; SMAA off\n", w, h);
            P.sm_ok = 0;
            return src;
        }
        P.sm_w = w;
        P.sm_h = h;
    }
    metrics[0] = 1.0f / (float)w;
    metrics[1] = 1.0f / (float)h;
    metrics[2] = (float)w;
    metrics[3] = (float)h;

    {   /* 1: luma edges */
        VkImageView v[1] = { src };
        VkSampler s[1] = { P.lin };
        begin_into(cmd, &P.edges, w, h);
        vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, P.sm_pipe[SM_EDGE]);
        bind_tex(cmd, P.sm_layout, 1, v, s);
        vkCmdPushConstants(cmd, P.sm_layout, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT,
                           0, sizeof metrics, metrics);
        vkCmdDraw(cmd, 3, 1, 0, 0);
        vkCmdEndRendering(cmd);
        barrier(cmd, &P.edges, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
    }
    {   /* 2: blending weights */
        VkImageView v[3] = { P.edges.view, P.area.view, P.search.view };
        VkSampler s[3] = { P.lin, P.lin, P.point };
        begin_into(cmd, &P.blend, w, h);
        vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, P.sm_pipe[SM_BLEND]);
        bind_tex(cmd, P.sm_layout, 3, v, s);
        vkCmdPushConstants(cmd, P.sm_layout, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT,
                           0, sizeof metrics, metrics);
        vkCmdDraw(cmd, 3, 1, 0, 0);
        vkCmdEndRendering(cmd);
        barrier(cmd, &P.blend, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
    }
    {   /* 3: neighbourhood blending */
        VkImageView v[2] = { src, P.blend.view };
        VkSampler s[2] = { P.lin, P.lin };
        begin_into(cmd, &P.out, w, h);
        vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, P.sm_pipe[SM_NEIGH]);
        bind_tex(cmd, P.sm_layout, 2, v, s);
        vkCmdPushConstants(cmd, P.sm_layout, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT,
                           0, sizeof metrics, metrics);
        vkCmdDraw(cmd, 3, 1, 0, 0);
        vkCmdEndRendering(cmd);
        barrier(cmd, &P.out, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
    }
    return P.out.view;
}

/* ---- scaling ------------------------------------------------------------ */

int vkp_draw(VkCommandBuffer cmd, VkImageView src, uint32_t src_w, uint32_t src_h,
             VkImageView dst, VkFormat dst_format, uint32_t dst_w, uint32_t dst_h,
             VkRect2D rect, int filter)
{
    VkRenderingAttachmentInfo ca = { VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO };
    VkRenderingInfo ri = { VK_STRUCTURE_TYPE_RENDERING_INFO };
    VkViewport vp;
    Push pc;

    if (!P.ok || !src || !dst || !rect.extent.width || !rect.extent.height)
        return 0;
    if (dst_format != P.fmt) {
        VkPipeline np = make_pipeline(P.vs, P.fs, P.layout, dst_format);
        if (!np) {
            P.ok = 0;
            return 0;
        }
        vkDestroyPipeline(P.dev, P.pipe, NULL);
        P.pipe = np;
        P.fmt = dst_format;
    }
    ca.imageView = dst;
    ca.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    ca.loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
    ca.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
    ri.renderArea.extent.width = dst_w;
    ri.renderArea.extent.height = dst_h;
    ri.layerCount = 1;
    ri.colorAttachmentCount = 1;
    ri.pColorAttachments = &ca;
    vkCmdBeginRendering(cmd, &ri);

    vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, P.pipe);
    bind_tex(cmd, P.layout, 1, &src, &P.lin);
    vp.x = (float)rect.offset.x;
    vp.y = (float)rect.offset.y;
    vp.width = (float)rect.extent.width;
    vp.height = (float)rect.extent.height;
    vp.minDepth = 0.0f;
    vp.maxDepth = 1.0f;
    vkCmdSetViewport(cmd, 0, 1, &vp);
    vkCmdSetScissor(cmd, 0, 1, &rect);
    pc.src_size[0] = (float)src_w;
    pc.src_size[1] = (float)src_h;
    pc.dst_size[0] = (float)rect.extent.width;
    pc.dst_size[1] = (float)rect.extent.height;
    pc.filt = filter;
    vkCmdPushConstants(cmd, P.layout, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof pc, &pc);
    vkCmdDraw(cmd, 3, 1, 0, 0);
    vkCmdEndRendering(cmd);
    return 1;
}
